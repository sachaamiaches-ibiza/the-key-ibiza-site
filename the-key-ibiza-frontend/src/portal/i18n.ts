const DICTS: Record<PortalLang, Dict> = { en, es, fr, de, it };

export type TFunc = (key: keyof typeof en, vars?: Record<string, string | number>) => string;

export function makeT(lang: PortalLang): TFunc {
  const dict = DICTS[lang] || en;
  return (key, vars) => {
    let s = dict[key as string] ?? en[key as string] ?? String(key);
    if (vars) for (const k in vars) s = s.replace(new RegExp(`\\{${k}\\}`, 'g'), String(vars[k]));
    return s;
  };
}
